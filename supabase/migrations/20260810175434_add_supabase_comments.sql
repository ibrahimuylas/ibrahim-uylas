create extension if not exists pgcrypto with schema extensions;

create table public.comment_threads (
  id bigint generated by default as identity primary key,
  path text not null unique check (path ~ '^/.*' and length(path) <= 500),
  title text not null check (length(title) between 1 and 300),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.comments (
  id bigint generated by default as identity primary key,
  thread_id bigint not null references public.comment_threads(id) on delete restrict,
  root_comment_id bigint references public.comments(id) on delete restrict,
  reply_to_comment_id bigint references public.comments(id) on delete restrict,
  author_name text not null check (length(author_name) between 1 and 80),
  body text not null check (length(body) between 1 and 5000),
  status text not null default 'published' check (status in ('published', 'hidden')),
  source text not null default 'native' check (source in ('native', 'disqus')),
  source_id text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  edited_at timestamptz,
  hidden_at timestamptz,
  last_activity_at timestamptz not null default now(),
  check (
    (root_comment_id is null and reply_to_comment_id is null) or
    (root_comment_id is not null and reply_to_comment_id is not null)
  )
);

create unique index comments_source_id_key
  on public.comments(source, source_id) where source_id is not null;
create index comments_thread_roots_idx
  on public.comments(thread_id, last_activity_at desc, id desc)
  where root_comment_id is null;
create index comments_root_replies_idx
  on public.comments(root_comment_id, created_at, id)
  where root_comment_id is not null;
create index comments_reply_target_idx on public.comments(reply_to_comment_id);

create table public.comment_contacts (
  comment_id bigint primary key references public.comments(id) on delete cascade,
  email text not null check (length(email) between 3 and 254),
  normalized_email_hash text not null,
  notify_replies boolean not null default false,
  email_verified_at timestamptz,
  verification_token_hash text,
  verification_expires_at timestamptz,
  unsubscribe_token_hash text not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index comment_contacts_email_hash_idx
  on public.comment_contacts(normalized_email_hash);
create unique index comment_contacts_verification_token_key
  on public.comment_contacts(verification_token_hash)
  where verification_token_hash is not null;
create unique index comment_contacts_unsubscribe_token_key
  on public.comment_contacts(unsubscribe_token_hash);

create table public.comment_email_outbox (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('owner_new_comment', 'verify_email', 'direct_reply')),
  comment_id bigint references public.comments(id) on delete cascade,
  recipient text not null check (length(recipient) between 3 and 254),
  payload jsonb not null default '{}'::jsonb,
  state text not null default 'pending' check (state in ('pending', 'sending', 'sent', 'failed')),
  attempt_count smallint not null default 0 check (attempt_count between 0 and 8),
  next_attempt_at timestamptz not null default now(),
  first_attempt_at timestamptz,
  provider_id text,
  last_error text,
  idempotency_key text not null unique,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index comment_email_outbox_due_idx
  on public.comment_email_outbox(next_attempt_at, id)
  where state in ('pending', 'failed') and attempt_count < 8;

create table public.comment_moderation_events (
  id bigint generated by default as identity primary key,
  comment_id bigint not null references public.comments(id) on delete restrict,
  admin_user_id uuid not null,
  action text not null check (action in ('hide', 'restore', 'edit', 'reply')),
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index comment_moderation_events_comment_idx
  on public.comment_moderation_events(comment_id, created_at desc);

